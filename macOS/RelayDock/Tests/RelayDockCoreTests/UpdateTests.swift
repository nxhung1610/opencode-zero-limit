import Foundation
import Testing

@testable import RelayDockCore

/// A test-only escape hatch: `Process` is not `Sendable`, but the reaper task
/// only calls the blocking, thread-safe `waitUntilExit` on it.
private final class UncheckedBox<T>: @unchecked Sendable {
    let value: T

    init(_ value: T) {
        self.value = value
    }
}

struct SemanticVersionTests {
    @Test func parsesPlainAndPrefixedTags() {
        #expect(SemanticVersion(tag: "0.2.0") == SemanticVersion(major: 0, minor: 2, patch: 0))
        #expect(SemanticVersion(tag: "v1.10.3") == SemanticVersion(major: 1, minor: 10, patch: 3))
    }

    @Test func rejectsSuffixedOrMalformedTags() {
        #expect(SemanticVersion(tag: "0.2") == nil)
        #expect(SemanticVersion(tag: "0.2.0-beta.1") == nil)
        #expect(SemanticVersion(tag: "1.2.x") == nil)
        #expect(SemanticVersion(tag: "") == nil)
    }

    @Test func ordersNumerically() {
        #expect(SemanticVersion(major: 0, minor: 10, patch: 0) > SemanticVersion(major: 0, minor: 9, patch: 9))
        #expect(SemanticVersion(major: 1, minor: 0, patch: 0) > SemanticVersion(major: 0, minor: 99, patch: 99))
        #expect(!(SemanticVersion(major: 0, minor: 2, patch: 0) > SemanticVersion(major: 0, minor: 2, patch: 0)))
    }
}

struct ChecksumFileTests {
    @Test func parsesShasumOutputAndSkipsNoise() {
        let zipDigest = String(repeating: "a", count: 64)
        let edgeDigest = String(repeating: "b", count: 64)
        let parsed = ChecksumFile.parse("""
        # generated by CI
        \(zipDigest)  RelayDock.app.zip

        \(edgeDigest) *relaydock-edge
        not-a-checksum-line
        """)
        #expect(parsed["RelayDock.app.zip"] == zipDigest)
        #expect(parsed["relaydock-edge"] == edgeDigest)
        #expect(parsed.count == 2)
    }

    @Test func hashesAFileLikeShasumDoes() throws {
        let url = FileManager.default.temporaryDirectory.appending(path: "relaydock-sha-\(UUID().uuidString)")
        defer { try? FileManager.default.removeItem(at: url) }
        try Data("hello\n".utf8).write(to: url)
        #expect(try ChecksumFile.sha256Hex(ofFileAt: url) == "5891b5b522d5df086d0ff0b110fbd9d21bb4fc7163af34d08286a2e846f6be03")
    }
}

struct UpdateFeedTests {
    @Test func parsesACompleteLatestRelease() {
        let json = """
        {
          "tag_name": "v0.2.0",
          "html_url": "https://github.com/nxhung1610/relaydock/releases/tag/v0.2.0",
          "assets": [
            {"name": "RelayDock.dmg", "browser_download_url": "https://example.com/RelayDock.dmg"},
            {"name": "RelayDock.app.zip", "browser_download_url": "https://example.com/RelayDock.app.zip"},
            {"name": "SHA256SUMS", "browser_download_url": "https://example.com/SHA256SUMS"}
          ]
        }
        """
        let release = UpdateFeed.parseLatest(Data(json.utf8))
        #expect(release?.version == SemanticVersion(major: 0, minor: 2, patch: 0))
        #expect(release?.zipURL.absoluteString == "https://example.com/RelayDock.app.zip")
        #expect(release?.checksumsURL.absoluteString == "https://example.com/SHA256SUMS")
        #expect(release?.releasePageURL.absoluteString == "https://github.com/nxhung1610/relaydock/releases/tag/v0.2.0")
    }

    @Test func requiresBothAssets() {
        let json = """
        {"tag_name": "v0.2.0", "html_url": "https://example.com/r", "assets": [
          {"name": "RelayDock.app.zip", "browser_download_url": "https://example.com/z"}
        ]}
        """
        #expect(UpdateFeed.parseLatest(Data(json.utf8)) == nil)
    }

    @Test func rejectsTagsThatAreNotPlainVersions() {
        let json = """
        {"tag_name": "nightly", "html_url": "https://example.com/r", "assets": [
          {"name": "RelayDock.app.zip", "browser_download_url": "https://example.com/z"},
          {"name": "SHA256SUMS", "browser_download_url": "https://example.com/s"}
        ]}
        """
        #expect(UpdateFeed.parseLatest(Data(json.utf8)) == nil)
    }

    @Test func feedURLHonoursTheOverride() {
        let override = UpdateFeed.defaultFeedURL(environment: ["RELAYDOCK_UPDATE_FEED": "https://example.com/feed"])
        #expect(override.absoluteString == "https://example.com/feed")
        let fallback = UpdateFeed.defaultFeedURL(environment: [:])
        #expect(fallback.absoluteString == "https://api.github.com/repos/nxhung1610/relaydock/releases/latest")
    }
}

struct UpdateInstallerTests {
    // MARK: - Fixtures

    private func makeTemporaryDirectory() throws -> URL {
        let url = FileManager.default.temporaryDirectory
            .appending(path: "relaydock-update-tests-\(UUID().uuidString)", directoryHint: .isDirectory)
        try FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
        return url
    }

    private func makeRelease(_ version: String) -> UpdateRelease {
        UpdateRelease(
            version: SemanticVersion(tag: version)!,
            tagName: "v\(version)",
            zipURL: URL(string: "https://example.com/RelayDock.app.zip")!,
            checksumsURL: URL(string: "https://example.com/SHA256SUMS")!,
            releasePageURL: URL(string: "https://example.com/releases/v\(version)")!
        )
    }

    private func makeFakeApp(
        at appURL: URL,
        version: String,
        bundleID: String = UpdateInstaller.supportedBundleID
    ) throws {
        let contents = appURL.appending(path: "Contents", directoryHint: .isDirectory)
        let macos = contents.appending(path: "MacOS", directoryHint: .isDirectory)
        try FileManager.default.createDirectory(at: macos, withIntermediateDirectories: true)
        let info: [String: Any] = [
            "CFBundleIdentifier": bundleID,
            "CFBundleShortVersionString": version,
            "CFBundleExecutable": "RelayDock",
            "CFBundlePackageType": "APPL",
        ]
        let data = try PropertyListSerialization.data(fromPropertyList: info, format: .xml, options: 0)
        try data.write(to: contents.appending(path: "Info.plist"))
        let executable = macos.appending(path: "RelayDock")
        try Data("#!/bin/sh\nexit 0\n".utf8).write(to: executable)
        try FileManager.default.setAttributes([.posixPermissions: 0o755], ofItemAtPath: executable.path)
    }

    private func zipApp(_ appURL: URL, to zipURL: URL) throws {
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/ditto")
        process.arguments = ["-c", "-k", "--keepParent", appURL.path, zipURL.path]
        try process.run()
        process.waitUntilExit()
        #expect(process.terminationStatus == 0)
    }

    // MARK: - Staging

    @Test func stagesAVerifiedRelease() throws {
        let root = try makeTemporaryDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let release = makeRelease("0.2.0")

        let app = root.appending(path: "build/RelayDock.app", directoryHint: .isDirectory)
        try makeFakeApp(at: app, version: "0.2.0")
        let zip = root.appending(path: "RelayDock.app.zip")
        try zipApp(app, to: zip)

        let digest = try ChecksumFile.sha256Hex(ofFileAt: zip)
        let staged = try UpdateInstaller.stage(
            zipFileURL: zip,
            checksums: "\(digest)  RelayDock.app.zip\n",
            release: release,
            workingDirectory: root.appending(path: "work", directoryHint: .isDirectory),
            verifySignature: { _ in true }
        )

        #expect(staged.release == release)
        #expect(staged.stagedAppURL.lastPathComponent == "RelayDock.app")
        #expect(FileManager.default.isExecutableFile(
            atPath: staged.stagedAppURL.appending(path: "Contents/MacOS/RelayDock").path
        ))
    }

    @Test func rejectsAHashMismatch() throws {
        let root = try makeTemporaryDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let release = makeRelease("0.2.0")

        let app = root.appending(path: "build/RelayDock.app", directoryHint: .isDirectory)
        try makeFakeApp(at: app, version: "0.2.0")
        let zip = root.appending(path: "RelayDock.app.zip")
        try zipApp(app, to: zip)

        let wrongDigest = String(repeating: "0", count: 64)
        #expect(throws: UpdateError.self) {
            try UpdateInstaller.stage(
                zipFileURL: zip,
                checksums: "\(wrongDigest)  RelayDock.app.zip\n",
                release: release,
                workingDirectory: root.appending(path: "work", directoryHint: .isDirectory),
                verifySignature: { _ in true }
            )
        }
    }

    @Test func rejectsAReleaseWithTheWrongVersion() throws {
        let root = try makeTemporaryDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let release = makeRelease("0.2.0")

        let app = root.appending(path: "build/RelayDock.app", directoryHint: .isDirectory)
        try makeFakeApp(at: app, version: "0.1.0")
        let zip = root.appending(path: "RelayDock.app.zip")
        try zipApp(app, to: zip)

        let digest = try ChecksumFile.sha256Hex(ofFileAt: zip)
        #expect(throws: UpdateError.self) {
            try UpdateInstaller.stage(
                zipFileURL: zip,
                checksums: "\(digest)  RelayDock.app.zip\n",
                release: release,
                workingDirectory: root.appending(path: "work", directoryHint: .isDirectory),
                verifySignature: { _ in true }
            )
        }
    }

    @Test func rejectsAFailedSignatureCheck() throws {
        let root = try makeTemporaryDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let release = makeRelease("0.2.0")

        let app = root.appending(path: "build/RelayDock.app", directoryHint: .isDirectory)
        try makeFakeApp(at: app, version: "0.2.0")
        let zip = root.appending(path: "RelayDock.app.zip")
        try zipApp(app, to: zip)

        let digest = try ChecksumFile.sha256Hex(ofFileAt: zip)
        #expect(throws: UpdateError.self) {
            try UpdateInstaller.stage(
                zipFileURL: zip,
                checksums: "\(digest)  RelayDock.app.zip\n",
                release: release,
                workingDirectory: root.appending(path: "work", directoryHint: .isDirectory),
                verifySignature: { _ in false }
            )
        }
    }

    // MARK: - Apply

    @Test func swapReplacesTheBundleAndCleansUpStaging() throws {
        let root = try makeTemporaryDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let parent = root.appending(path: "apps", directoryHint: .isDirectory)
        try FileManager.default.createDirectory(at: parent, withIntermediateDirectories: true)
        let target = parent.appending(path: "RelayDock.app", directoryHint: .isDirectory)
        try makeFakeApp(at: target, version: "0.1.0")
        let stagingRoot = root.appending(path: "updates", directoryHint: .isDirectory)
        let staged = stagingRoot.appending(path: "0.2.0/staged/RelayDock.app", directoryHint: .isDirectory)
        try makeFakeApp(at: staged, version: "0.2.0")

        try UpdateInstaller.apply(stagedApp: staged, targetApp: target, stagingRoot: stagingRoot)

        let plist = try PropertyListSerialization.propertyList(
            from: Data(contentsOf: target.appending(path: "Contents/Info.plist")),
            options: [],
            format: nil
        ) as? [String: Any]
        #expect(plist?["CFBundleShortVersionString"] as? String == "0.2.0")
        #expect(!FileManager.default.fileExists(atPath: stagingRoot.path))
        let siblings = try FileManager.default.contentsOfDirectory(atPath: parent.path)
        #expect(siblings == ["RelayDock.app"])
    }

    @Test func swapOnAReadOnlyParentLeavesTheOldApp() throws {
        let root = try makeTemporaryDirectory()
        defer {
            try? FileManager.default.setAttributes(
                [.posixPermissions: 0o755],
                ofItemAtPath: root.appending(path: "apps").path
            )
            try? FileManager.default.removeItem(at: root)
        }
        let parent = root.appending(path: "apps", directoryHint: .isDirectory)
        try FileManager.default.createDirectory(at: parent, withIntermediateDirectories: true)
        let target = parent.appending(path: "RelayDock.app", directoryHint: .isDirectory)
        try makeFakeApp(at: target, version: "0.1.0")
        let staged = root.appending(path: "staged/RelayDock.app", directoryHint: .isDirectory)
        try makeFakeApp(at: staged, version: "0.2.0")

        try FileManager.default.setAttributes([.posixPermissions: 0o555], ofItemAtPath: parent.path)
        #expect(throws: UpdateError.self) {
            try UpdateInstaller.apply(
                stagedApp: staged,
                targetApp: target,
                stagingRoot: staged.deletingLastPathComponent()
            )
        }
        try FileManager.default.setAttributes([.posixPermissions: 0o755], ofItemAtPath: parent.path)

        let plist = try PropertyListSerialization.propertyList(
            from: Data(contentsOf: target.appending(path: "Contents/Info.plist")),
            options: [],
            format: nil
        ) as? [String: Any]
        #expect(plist?["CFBundleShortVersionString"] as? String == "0.1.0")
    }

    // MARK: - Helper protocol

    @Test func helperRequestParsesTheFlagAndPayload() {
        let request = UpdateInstaller.helperRequest(from: [
            "/Applications/RelayDock.app/Contents/MacOS/RelayDock",
            "--apply-update",
            "/tmp/staged/RelayDock.app",
            "/Applications/RelayDock.app",
            "4242",
            "/tmp/updates",
            "/tmp/update-status.txt",
        ])
        #expect(request?.parentPID == 4242)
        #expect(request?.stagedAppURL.path == "/tmp/staged/RelayDock.app")
        #expect(request?.targetAppURL.path == "/Applications/RelayDock.app")
        #expect(request?.stagingRoot.path == "/tmp/updates")
        #expect(request?.statusFileURL.path == "/tmp/update-status.txt")

        #expect(UpdateInstaller.helperRequest(from: ["RelayDock"]) == nil)
        #expect(UpdateInstaller.helperRequest(from: ["RelayDock", "--other"]) == nil)
    }

    @Test func waitForExitReturnsWhenTheProcessLeaves() async throws {
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/bin/sleep")
        process.arguments = ["0.3"]
        try process.run()
        let boxed = UncheckedBox(process)
        let reaper = Task.detached { boxed.value.waitUntilExit() }

        #expect(UpdateInstaller.waitForExit(of: process.processIdentifier, timeout: 10))
        await reaper.value
    }

    @Test func waitForExitTimesOutOnALiveProcess() throws {
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/bin/sleep")
        process.arguments = ["5"]
        try process.run()
        defer {
            process.terminate()
            process.waitUntilExit()
        }

        #expect(!UpdateInstaller.waitForExit(of: process.processIdentifier, timeout: 0.3))
    }

    @Test func runHelperSwapsAfterTheParentExits() async throws {
        let root = try makeTemporaryDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let parent = root.appending(path: "apps", directoryHint: .isDirectory)
        try FileManager.default.createDirectory(at: parent, withIntermediateDirectories: true)
        let target = parent.appending(path: "RelayDock.app", directoryHint: .isDirectory)
        try makeFakeApp(at: target, version: "0.1.0")
        let stagingRoot = root.appending(path: "updates", directoryHint: .isDirectory)
        let staged = stagingRoot.appending(path: "staged/RelayDock.app", directoryHint: .isDirectory)
        try makeFakeApp(at: staged, version: "0.2.0")
        let statusFile = root.appending(path: "update-status.txt")

        let parentProcess = Process()
        parentProcess.executableURL = URL(fileURLWithPath: "/bin/sleep")
        parentProcess.arguments = ["0.2"]
        try parentProcess.run()
        let boxed = UncheckedBox(parentProcess)
        let reaper = Task.detached { boxed.value.waitUntilExit() }

        let request = UpdateHelperRequest(
            stagedAppURL: staged,
            targetAppURL: target,
            parentPID: parentProcess.processIdentifier,
            stagingRoot: stagingRoot,
            statusFileURL: statusFile
        )
        let code = UpdateInstaller.runHelper(request, relaunch: { _ in })
        await reaper.value

        #expect(code == 0)
        let status = try String(contentsOf: statusFile, encoding: .utf8)
        #expect(status.trimmingCharacters(in: .whitespacesAndNewlines) == "ok")
        let plist = try PropertyListSerialization.propertyList(
            from: Data(contentsOf: target.appending(path: "Contents/Info.plist")),
            options: [],
            format: nil
        ) as? [String: Any]
        #expect(plist?["CFBundleShortVersionString"] as? String == "0.2.0")
    }
}
